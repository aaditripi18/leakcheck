"""Write splits/README.md, the index of the clean-split lists, from splits/*.json. Never edit it by hand.

    python scripts/splits_index.py

Each list's files (.drop.txt.gz, .drop_source.txt.gz, .test_source.txt.gz) are published as
assets of the GitHub release `clean-splits`; the index records the SHA-256 of each, so a
download can be checked.
"""
from __future__ import annotations

import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SPLITS = ROOT / "splits"
RELEASE = "https://github.com/aaditripi18/leakcheck/releases/download/clean-splits"


def sha256(p: Path) -> str:
    return hashlib.sha256(p.read_bytes()).hexdigest()


def main() -> None:
    rows, files = [], {}
    for j in sorted(SPLITS.glob("*.json")):
        if j.name == "index.json":
            continue
        d = json.loads(j.read_text(encoding="utf-8"))
        slug = j.stem
        near = "exact + near" if isinstance(d["near"], dict) else "exact only (near pending)"
        ok = all(v["ok"] for v in d["recheck"].values())
        g = d.get("measured_gap") or {}
        gap = f"{g['full_gap_macro_f1'] * 100:+.1f}" if "full_gap_macro_f1" in g else ""
        rows.append((d["case"], d["split"], d["n_test"], d["n_drop"], near, ok, gap))
        files[d["case"]] = {f.name: sha256(f) for f in sorted(SPLITS.glob(f"{slug}.*.gz"))}
    (SPLITS / "index.json").write_text(json.dumps(files, indent=1) + "\n", encoding="utf-8")
    out = ["# Clean benchmark splits", "",
           "Generated by `scripts/splits_index.py` from `splits/*.json`. Do not edit by hand.", "",
           "For each benchmark: which test rows have an exact or near copy in the training set. Drop them "
           "and the test set no longer overlaps training; the training set is left as published. Each list "
           "was produced by `leakcheck clean` (conflicts kept, so training rows do not change) and re-checked "
           "on every row of the cleaned split (`recheck` in the JSON).", "",
           "**Use it without leakcheck.** `<case>.drop_source.txt.gz` lists the dropped rows by position in "
           "the original data, numbered as the JSON's `source_numbering` says. For a random split, "
           "`<case>.test_source.txt.gz` lists the test rows and `split_rule` gives the scikit-learn call that "
           "rebuilds them. Download the lists from the "
           f"[`clean-splits` release]({RELEASE.rsplit('/download', 1)[0]}/tag/clean-splits); `index.json` "
           "has each file's SHA-256.", "",
           "**Or rebuild the files:** `python -m experiments.clean_splits write <case> --out DIR` writes "
           "`train.csv` and the cleaned `test.csv` from the pinned data.", "",
           "| Case | Split | Test rows | Dropped | Share | Search | Re-check | Gap (pts) |",
           "|---|---|--:|--:|--:|---|---|--:|"]
    for case, split, n, k, near, ok, gap in rows:
        out.append(f"| {case} | {split} | {n:,} | {k:,} | {k / n:.1%} | {near} | {'clean' if ok else 'FAILED'} "
                   f"| {gap} |")
    out += ["", "*Gap*: macro-F1 on the whole test set minus without the leaked rows, from E13/E14 (12 cells) "
                "where measured; the E2 summaries are in docs/RESULTS.md. Near copies: RMS distance <= 0.01 in "
                "leakcheck's scaled space, Jaccard >= 0.8 for text.", ""]
    (SPLITS / "README.md").write_text("\n".join(out), encoding="utf-8")
    print(f"wrote splits/README.md ({len(rows)} cases) and splits/index.json")


if __name__ == "__main__":
    main()
